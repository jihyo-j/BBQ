#!/usr/bin/env python3
"""Measure the labels in a rendered legend strip and write their exact widths
back for the next pass, so the hand-laid row uses real type widths instead of
an average-glyph estimate."""
import sys, os, pymupdf

for pdf in sys.argv[1:]:
    p = pymupdf.open(pdf)[0]
    spans = sorted((s["bbox"][0], s["bbox"][2])
                   for b in p.get_text("dict")["blocks"]
                   for l in b.get("lines", []) for s in l["spans"])
    if not spans:
        continue
    out = f"w_{os.path.basename(pdf)[:-4]}.gp"
    with open(out, "w") as f:
        f.write(f"# measured from {os.path.basename(pdf)}; regenerated by fixwidths.py\n")
        f.write(f"array LWID[{len(spans)}] = [" +
                ", ".join(f"{x1-x0:.2f}" for x0, x1 in spans) + "]\n")
    print(f"{out}: {[round(x1-x0,1) for x0,x1 in spans]}")
