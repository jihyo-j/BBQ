#!/usr/bin/env python3
"""Derive the stacked-bar percentages from the group counts.

vldb_pct.dat used to be maintained by hand next to vldb_corpora.dat, which is
how its slab order drifted away from the legend's.  Regenerate it instead:

    python3 make_vldb_pct.py > vldb_pct.dat

Slabs run bottom to top in increasing distance from "Transformer / modern API",
the same order the legend reads, so a single-hue ramp can carry that order.
"""
import pathlib

SRC = pathlib.Path(__file__).with_name("vldb_corpora.dat")

print("# Generated by make_vldb_pct.py from vldb_corpora.dat -- do not hand-edit.")
print("# Cumulative shares, bottom slab first, in legend order:")
print("#   modern < modern+other_learned < +conventional < +unresolved (= 100).")
print("# year  cum_modern  cum_other  cum_conv  cum_unres  modern_pct  modern_label")
for line in SRC.read_text().splitlines():
    if line.startswith("#") or not line.strip():
        continue
    year, _papers, n, conv, modern, other, unres = line.split()
    n = int(n)
    cum = []
    run = 0.0
    for c in (modern, other, conv, unres):
        run += 100.0 * int(c) / n
        cum.append(run)
    pct = 100.0 * int(modern) / n
    # No percent sign: the y axis already reads "Dataset share (%)", and at a
    # 19.4pt bar "19.8%" is 20.6pt wide, so the sign pushed the white glyphs
    # off the slab and onto the white page.
    label = "" if int(modern) == 0 else (f"{pct:.0f}" if abs(pct - round(pct)) < 0.05
                                         else f"{pct:.1f}")
    print(f"{year} {cum[0]:6.2f} {cum[1]:6.2f} {cum[2]:6.2f} {cum[3]:6.2f} "
          f"{pct:5.1f} \"{label}\"")
