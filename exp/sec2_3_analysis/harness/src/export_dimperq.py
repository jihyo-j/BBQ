"""Write the quantizer x MRL-dimension score-error grid as a gnuplot table.

  p_dimperq.dat     d, f, c_Q_iso, then one c_Q column per quantizer
  p_dimperq_n.dat   the same c_Q columns divided by their own value at d=32,
                    which is how fast each quantizer's error falls rather than
                    where it starts

Column order fixes the line styles in fig_dimperq.gp and follows Figure 3(d):
the byte-matched codes first (d/8 bytes, RaBitQ +4), then the two scalar
quantizers, which buy their lower error with 4x and 8x the bytes.
"""
import os, sys, json
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import OUT

GP = "/home/sieun/projects/BBQETA/gp"
ARMS = [("sym_bq", "Sym-BQ"), ("adc_bq", "ADC-BQ"), ("tq1", "TQ-1bit"),
        ("adc_bq_c", "ADC+c"), ("adc_bq_cb", "ADC+cs"),
        ("rabitq1", "RaBitQ"), ("pq", "PQ"), ("opq", "OPQ"),
        ("sq4", "SQ-4bit"), ("sq8", "SQ-8bit")]


COLOR = {"Sym-BQ": "#262626", "ADC-BQ": "#E8336D", "TQ-1bit": "#9933E6",
         "ADC+c": "#7A7AF5", "ADC+cs": "#0A0AF0", "RaBitQ": "#1A9850",
         "PQ": "#D97706", "OPQ": "#00919B", "SQ-4bit": "#A8A8A8",
         "SQ-8bit": "#A8A8A8", "isotropic": "#6E6E6E"}
# drawn curves, in no particular order; ADC+c (centre, no scale) and SQ-8bit
# are measured and tabulated but not drawn -- the first sits on top of ADC+cs
# and the second, at eight times the bytes and c_Q near 0.005, would cost the
# panel a decade and a half of empty axis.
PLOT = ["isotropic", "Sym-BQ", "ADC-BQ", "TQ-1bit", "ADC+cs", "RaBitQ", "PQ",
        "OPQ", "SQ-4bit"]
NICE_LAB = {"ADC+cs": "+ctr+scale"}


def labels(path, last, lx, gap=1.18):
    """Write the right-hand curve labels at each curve's own end value, moved as
    little as possible subject to no two being closer than `gap` on the log
    axis -- a legend box would need nine entries and the curves end in the order
    of the labels.  A one-sided pass (push each label below the one above) walks
    the whole block downward and leaves the lowest labels well off their curves;
    with u_i = log(y_i) + i*log(gap) the separation constraint is exactly "u is
    non-increasing", so the L2-closest legal placement is an isotonic fit of u.
    """
    from scipy.optimize import isotonic_regression
    v = sorted(((last[n], n) for n in PLOT if n in last), reverse=True)
    g = np.log(gap)
    u = np.array([np.log(a) + i * g for i, (a, _) in enumerate(v)])
    w = isotonic_regression(u, increasing=False).x
    y = np.exp(w - g * np.arange(len(v)))
    with open(path, "w") as f:
        f.write("# right-hand curve labels, generated by export_dimperq.py\n")
        for i, (_, n) in enumerate(v, start=1):
            f.write(f'set label {i} "{NICE_LAB.get(n, n)}" at {lx},{y[i-1]:.4f} '
                    f'left font FN tc rgb "{COLOR[n]}" front\n')
    return path


def main(key="msmarco_qw8"):
    res = json.load(open(f"{OUT}/dimperq_{key}.json"))
    rows = res["rows"]
    have = [(a, n) for a, n in ARMS if a in rows[0]["arms"]]
    head = "# d  f  c_Q_iso  " + "  ".join(n for _, n in have)

    def write(path, norm):
        base = {a: rows[0]["arms"][a]["c_Q"] for a, _ in have}
        with open(path, "w") as f:
            f.write(f"# {key}: N={res['N']} nq={res['nq']}, MRL truncation of "
                    f"{res['encoder']} on {res['corpus']}\n")
            f.write(head + ("  (each relative to its own d=32)\n" if norm else "\n"))
            for r in rows:
                v = [r["arms"][a]["c_Q"] / (base[a] if norm else 1.0) for a, _ in have]
                f.write(f"{r['d']:5d} {r['f_sign_cos']:.4f} {r['c_Q_iso']:.4f} "
                        + " ".join(f"{x:.4f}" for x in v) + "\n")
        return path

    write(f"{GP}/p_dimperq.dat", False)
    write(f"{GP}/p_dimperq_n.dat", True)
    last = {n: rows[-1]["arms"][a]["c_Q"] for a, n in have}
    last["isotropic"] = rows[-1]["c_Q_iso"]
    labels(f"{GP}/p_dimperq_lab.gp", last, lx=rows[-1]["d"] * 1.16)
    print(f"wrote p_dimperq{{,_n}}.dat: {len(rows)} dims x {len(have)} quantizers")
    span = f"d={rows[0]['d']}/d={rows[-1]['d']}"
    print(f"{'':22s}" + "".join(f"{r['d']:>8d}" for r in rows) + f"    {span}")
    for a, n in have:
        v = [r["arms"][a]["c_Q"] for r in rows]
        print(f"  {n:20s}" + "".join(f"{x:8.4f}" for x in v)
              + f"    {v[0]/v[-1]:8.2f}x")
    v = [r["c_Q_iso"] for r in rows]
    print(f"  {'isotropic ref':20s}" + "".join(f"{x:8.4f}" for x in v)
          + f"    {v[0]/v[-1]:8.2f}x")


if __name__ == "__main__":
    main(*(sys.argv[1:] or []))
