#!/usr/bin/env python3
"""Uniform bottom legend for all BBQ figures.

Text widths come from the Helvetica AFM (Liberation Sans is metric-
compatible), so every figure gets identical sample length, gaps, row
pitch and font size; column widths depend only on the label text.

Spec file (one entry per line, '#' comments allowed):
    nrows = 2                 # optional, default 1 (entries fill column-major)
    ytop  = 14                # optional, pt from canvas bottom to top of legend
    ls=1 | SymBQ | lp         # kinds: lp (line+point)  l (line)  p (point)
    ls=3 | query prep | box   #        box (solid swatch)  hbox (hatched swatch)
    ls=0 | | skip             #        skip (empty cell, to align columns)
Output: gnuplot commands (screen coords) -> load it, then `eval DRAWSCREEN`.

Usage: legend.py spec.txt W [H] > fig_legend.gp
"""
import re, sys, os

AFM = os.path.join(os.path.dirname(__file__), 'Helvetica.afm')
W = {}
UNI = {}
for l in open(AFM, encoding='latin1'):
    m = re.match(r'C (-?\d+) ; WX (\d+) ; N (\S+)', l)
    if m:
        W[m.group(3)] = int(m.group(2))
NAMES = {' ': 'space', '.': 'period', ',': 'comma', '-': 'hyphen', '+': 'plus', '(': 'parenleft',
         ')': 'parenright', '/': 'slash', ':': 'colon', '@': 'at', '%': 'percent', '=': 'equal',
         '_': 'underscore', '*': 'asterisk', '&': 'ampersand', '#': 'numbersign', "'": 'quotesingle',
         '0': 'zero', '1': 'one', '2': 'two', '3': 'three', '4': 'four', '5': 'five', '6': 'six',
         '7': 'seven', '8': 'eight', '9': 'nine', '−': 'minus', '≥': 'greaterequal',
         '≤': 'lessequal', '×': 'multiply', '[': 'bracketleft', ']': 'bracketright'}

def textw(s, size):
    s = re.sub(r'\\(.)', r'\1', s)          # drop gnuplot escapes
    tot = 0
    for ch in s:
        n = NAMES.get(ch, ch)
        tot += W.get(n, 556)
    return tot * size / 1000.0

# ---- uniform geometry [pt] ----
FK = 6.5          # must match common.gp
SAMPLE = 14.0     # sample length (line) / swatch width
SWH = 5.0         # swatch height
GAP_ST = 3.0      # sample -> text
GAP_COL = 9.0     # text end -> next column's sample
ROW = 8.5         # row pitch

def main():
    global FK, SAMPLE, SWH, GAP_ST, GAP_COL, ROW
    spec = open(sys.argv[1]).read().splitlines()
    Wc = float(sys.argv[2])
    nrows, ytop, ents = 1, 14.0, []
    for l in spec:
        l = l.split('#')[0].strip() if not l.strip().startswith('ls=') else l.strip()
        if not l:
            continue
        m = re.match(r'(nrows|ytop|scale)\s*=\s*([\d.]+)', l)
        if m:
            if m.group(1) == 'nrows': nrows = int(m.group(2))
            elif m.group(1) == 'scale':   # optional: enlarge legend text + geometry (default 1)
                s = float(m.group(2)); FK *= s; SAMPLE *= s; SWH *= s; GAP_ST *= s; GAP_COL *= s; ROW *= s
            else: ytop = float(m.group(2))
            continue
        parts = [p.strip() for p in l.split('|')]
        ls = int(parts[0].split('=')[1])
        ents.append((ls, parts[1], parts[2] if len(parts) > 2 else 'lp'))
    ncols = -(-len(ents) // nrows)
    cols = [ents[c*nrows:(c+1)*nrows] for c in range(ncols)]
    colw = [SAMPLE + GAP_ST + max(textw(e[1], FK) for e in col) for col in cols]
    total = sum(colw) + GAP_COL * (ncols - 1)
    x = (Wc - total) / 2.0
    out = ['# --- generated by legend.py (uniform legend) ---']
    tag = 100
    for c, col in enumerate(cols):
        for r, (ls, label, kind) in enumerate(col):
            yc = ytop - ROW * (r + 0.5)
            if kind == 'skip':
                continue
            x0, x1 = x, x + SAMPLE
            if kind in ('lp', 'l'):
                out.append(f'set arrow {tag} from screen sx({x0:.2f}),sy({yc:.2f}) to screen sx({x1:.2f}),sy({yc:.2f}) nohead ls {ls} front'); tag += 1
            if kind in ('lp', 'p'):
                out.append(f'set label {tag} "" at screen sx({(x0+x1)/2:.2f}),sy({yc:.2f}) point ls {ls} lw MLW front'); tag += 1
            if kind == 'box':
                out.append(f'set object {tag} rect from screen sx({x0+2:.2f}),sy({yc-SWH/2:.2f}) to screen sx({x1-2:.2f}),sy({yc+SWH/2:.2f}) fc ls {ls} fs solid 1.0 border lc ls {ls} lw MLW front'); tag += 1
            if kind == 'hbox':
                out.append(f'set object {tag} rect from screen sx({x0+2:.2f}),sy({yc-SWH/2:.2f}) to screen sx({x1-2:.2f}),sy({yc+SWH/2:.2f}) fc ls {ls} fs pattern HATCH border lc ls {ls} lw MLW front'); tag += 1
            out.append(f'set label {tag} "{label}" at screen sx({x1+GAP_ST:.2f}),sy({yc:.2f}) left font ",{FK:g}" front'); tag += 1
        x += colw[c] + GAP_COL
    out.append(f'# legend: {ncols} cols x {nrows} rows, width {total:.1f}pt, height {ROW*nrows:.1f}pt')
    print('\n'.join(out))

if __name__ == '__main__':
    main()
