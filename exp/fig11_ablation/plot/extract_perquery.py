# perquery: (a) per-query R* vs z10 scatter (raster cloud) + dataset centroids
#           (b) DBpedia z10 vs #relevant docs (raster points) + binned median/IQR
import sys, re, zlib, struct; sys.path.insert(0, '../tools'); import figlib as F, pdfvec
SRC = '../bbq_src/figures/bbq/perquery.pdf'
fig = F.Fig(SRC)
a, b = fig.axes
b.calibrate('x', kind='log', pairs=[(164.69, 1.0), (187.48, 10.0), (210.26, 100.0)])

# ---------- raster point clouds -> RGBA PNG ----------
data = open(SRC, 'rb').read(); objs = pdfvec.load_objects(data)
def unfilter(raw, w, h, bpp, rowbytes):
    out = bytearray(); prev = bytearray(rowbytes); i = 0
    for _ in range(h):
        ft = raw[i]; i += 1
        row = bytearray(raw[i:i + rowbytes]); i += rowbytes
        for x in range(rowbytes):
            A = row[x - bpp] if x >= bpp else 0; B = prev[x]; C = prev[x - bpp] if x >= bpp else 0
            if ft == 1: row[x] = (row[x] + A) & 255
            elif ft == 2: row[x] = (row[x] + B) & 255
            elif ft == 3: row[x] = (row[x] + ((A + B) >> 1)) & 255
            elif ft == 4:
                p = A + B - C; pa, pb, pc = abs(p - A), abs(p - B), abs(p - C)
                row[x] = (row[x] + (A if pa <= pb and pa <= pc else B if pb <= pc else C)) & 255
        out += row; prev = row
    return out
def image(num):
    o = objs[num]
    w = int(re.search(rb'/Width (\d+)', o).group(1)); h = int(re.search(rb'/Height (\d+)', o).group(1))
    bpc = int(re.search(rb'/BitsPerComponent (\d+)', o).group(1))
    raw = pdfvec.stream_of(o)
    if b'/DeviceGray' in o[:300]:
        return w, h, unfilter(raw, w, h, 1, w), 'gray'
    if b'/Indexed' in o[:300]:
        pal = re.search(rb'/Indexed /DeviceRGB 1 \((.*?)\) \]', o, re.S).group(1)
        rows = unfilter(raw, w, h, 1, (w + 7) // 8)
        rb = (w + 7) // 8; px = bytearray()
        for y in range(h):
            for x in range(w):
                bit = (rows[y * rb + x // 8] >> (7 - x % 8)) & 1
                px += pal[3 * bit:3 * bit + 3]
        return w, h, px, 'rgb'
    return w, h, unfilter(raw, w, h, 3, 3 * w), 'rgb'
def smask_of(num):
    return int(re.search(rb'/SMask (\d+) 0 R', objs[num]).group(1))
def write_png(fn, w, h, rgba):
    raw = b''.join(b'\x00' + bytes(rgba[y * 4 * w:(y + 1) * 4 * w]) for y in range(h))
    def chunk(t, d): return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    open(fn, 'wb').write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
imgnums = {}
for k, v in objs.items():
    m = re.search(rb'/XObject\s*<<(.*?)>>', v, re.S)
for name, num in pdfvec.parse_dict_refs(pdfvec.inline_or_ref_dict(objs, objs[8], b'XObject')).items():
    if b'/Image' in objs[num][:200]: imgnums[name] = num
out = []
for im in fig.o['images']:
    num = imgnums[im['name']]
    w, h, rgb, _ = image(num); _, _, al, _ = image(smask_of(num))
    rgba = bytearray()
    for i in range(w * h):
        rgba += rgb[3 * i:3 * i + 3] + bytes([al[i]])
    fn = 'perquery_cloud_%s.png' % ('a' if im['ctm'][4] < 140 else 'b')
    write_png(fn, w, h, rgba)
    c = im['ctm']
    ax = a if c[4] < 140 else b
    # placement as fractions of the panel box (image y axis runs top->bottom in PDF)
    bx = ax.box
    out.append((fn, w, h, (c[4] - bx[0]) / (bx[2] - bx[0]), (c[5] - bx[1]) / (bx[3] - bx[1]),
                c[0] / (bx[2] - bx[0]), c[3] / (bx[3] - bx[1])))
    print(fn, w, h, out[-1][3:])
with open('perquery_cloud.gp', 'w') as f:
    f.write('# raster placement (fractions of the panel frame), generated by extract_perquery.py\n')
    for fn, w, h, fx, fy, fw, fh in out:
        t = fn[-5]
        f.write(f'CLOUD_{t} = "{fn}"; CW_{t} = {w}; CH_{t} = {h}; CX_{t} = {fx:.6f}; CY_{t} = {fy:.6f}; CFW_{t} = {fw:.6f}; CFH_{t} = {fh:.6f}\n')

# ---------- vector parts ----------
blocks = []
# (a) dataset centroids: white-filled big markers
names = {'#E8336E': 'quora', '#0000FF': 'dbpedia', '#FF8000': 'msmarco', '#9B1FE8': 'nq', '#00A650': 'fever'}
for p in fig.o['paths']:
    if p['paint'] == 'B' and p['fill'] == [1.0, 1.0, 1.0] and len(p['ops']) >= 4:
        bb = F.bbox(p); cx, cy = (bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2
        col = F.hexc(p['stroke'])
        if a.inside(cx, cy):
            # triangles: centroid of vertices, not bbox centre
            v = F.verts(p)
            if len(set(v)) == 3: cx = sum(x for x, y in set(v)) / 3; cy = sum(y for x, y in set(v)) / 3
            blocks.append((f'cent_{names[col]}', [a.xy(cx, cy)]))
# (b) median line + markers + IQR bars
ser = b.series()
line = [s for s in ser if s.color == '#000000'][0]
blocks.append(('median_b', line.pts))
iqr = [s for s in ser if s.color == '#737373']
blocks.append(('iqr_b', [(s.pts[0][0], min(s.pts[0][1], s.pts[1][1]), max(s.pts[0][1], s.pts[1][1])) for s in iqr]))
print('a', a.cal['x']['lo'], a.cal['x']['hi'], a.cal['y']['lo'], a.cal['y']['hi'])
print('b', b.cal['x']['lo'], b.cal['x']['hi'], b.cal['y']['lo'], b.cal['y']['hi'])
F.write_blocks('perquery.dat', blocks)
