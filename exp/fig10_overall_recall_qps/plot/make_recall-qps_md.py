#!/usr/bin/env python3
"""recall-qps_md: MS MARCO + DBpedia rows (panels i..p) of recall-qps_main, plus PipeANN-RaBitQ1bit.
Inputs : recall-qps_main.dat / recall-qps_main_panels.gp / recall-qps_main.legend (unchanged)
         argv[1] = spann_pipeann/all_search_results.csv (family pipeann_native_rabitq_1bit_c16, T=1)
Outputs: recall-qps_md.dat / recall-qps_md_panels.gp / recall-qps_md.legend
PipeANN curve = all measured points in Lsearch order; markers = 5 evenly spaced points."""
import csv, re, sys
SRC = sys.argv[1]
PANEL = dict(zip('ijklmnop', ['msmarco_openai1536', 'msmarco_bge1024', 'msmarco_qwen1024', 'msmarco_e5mistral4096',
                              'dbpedia_openai1536', 'dbpedia_bge1024', 'dbpedia_qwen1024', 'dbpedia_e5mistral4096']))
rows = [r for r in csv.DictReader(open(SRC)) if r['family'] == 'pipeann_native_rabitq_1bit_c16']
# PipeANN blocks (smoothed) come from recall-qps_main.dat (add_recall-qps_main_pipeann.py)
dat = open('recall-qps_main.dat').read()
assert 'pipeann_i_curve' in dat
open('recall-qps_md.dat', 'w').write(dat)

src = open('recall-qps_main_panels.gp').read()
blocks = re.split(r'(?m)^(?=# \([a-p]\)\n)', src)
keep = [b for b in blocks if re.match(r'# \(([i-p])\)\n', b)]
out = ['# generated by make_recall-qps_md.py from recall-qps_main_panels.gp -- do not edit by hand\n']
for b in keep:
    p = b[3]
    b = b.replace('PYB(2)', 'PYB(0)').replace('PYB(3)', 'PYB(1)')
    assert b.count('pipeann_') == 2, p
    out.append(b)
open('recall-qps_md_panels.gp', 'w').write(''.join(out))

leg = open('recall-qps_main.legend').read()
leg = leg.replace('ls=7 | HNSW-RaBitQ1 | lp', 'ls=7 | HNSW-RaBitQ1bit | lp').replace('ls=6 | RaBitQ-SSD | l', 'ls=6 | RaBitQ-SSD 9bit | l')
leg = leg.replace('ls=8 | DiskANN-RaBitQ | lp', 'ls=8 | DiskANN-RaBitQ1bit | lp\nls=4 | PipeANN-RaBitQ1bit | lp')
assert 'PipeANN' in leg and 'HNSW-RaBitQ1bit' in leg
open('recall-qps_md.legend', 'w').write(leg)
