# recall-qps_main: 4x4 Recall@10-vs-QPS grid, data recovered from the original matplotlib PDF
import sys, math; sys.path.insert(0, '../tools'); import figlib as F
SRC = '../bbq_src/figures/bbq/recall-qps_main.pdf'
PINK, PURP, BLUE, GREEN = '#E8336E', '#9B1FE8', '#0000FF', '#00A650'
# (id, label, shape, color) in legend order (column-major, 2 rows)
METHODS = [('adcbq', 'BBQ', 'square', PINK), ('esbbq', 'ES-BBQ', 'circle', PINK),
           ('tq', 'TurboQuant1 FP@60', 'circle', PURP), ('mrq', 'MRQ-SSD', 'diamond', PURP),
           ('rbq7', 'RaBitQ-7bit', 'triangle_up', BLUE), ('rbqssd', 'RaBitQ-SSD', 'triangle_right', BLUE),
           ('hnswrbq', 'HNSW-RaBitQ1', 'circle', BLUE), ('dannrbq', 'DiskANN-RaBitQ', 'triangle_down', BLUE),
           ('spann', 'SPANN', 'square', GREEN), ('dannpq', 'DiskANN-PQ', 'triangle_down', GREEN),
           ('fpq', 'Faiss PQ', 'pentagon', GREEN), ('fopq', 'Faiss OPQ', 'hexagon', GREEN)]

def seg_dist(p, a, b):
    ax, ay = a; bx, by = b; px, py = p
    dx, dy = bx - ax, by - ay
    L = dx * dx + dy * dy
    t = 0 if L == 0 else max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L))
    return math.hypot(ax + t * dx - px, ay + t * dy - py)

def dist(pts, poly):
    return sum(min(seg_dist(p, poly[i], poly[i + 1]) for i in range(len(poly) - 1)) for p in pts) / len(pts)

fig = F.Fig(SRC)
assert len(fig.axes) == 16
blocks, info = [], []
for k, ax in enumerate(fig.axes):
    tag = chr(ord('a') + k)
    mk = {}
    for m in ax.markers():
        mid = [M[0] for M in METHODS if M[2] == m.shape and M[3] == m.color]
        assert len(mid) == 1, (tag, m)
        mk.setdefault(mid[0], []).append(m)
    curves = [s for s in ax.series() if s.color in (PINK, PURP, BLUE, GREEN)]
    # assign curves to methods greedily by marker-to-polyline distance (pixel space)
    pairs = []
    for ci, s in enumerate(curves):
        for mid, ms in mk.items():
            if ms[0].color != s.color:
                continue
            pairs.append((dist([m.px for m in ms], s.raw), ci, mid))
    pairs.sort()
    used_c, used_m, assign = set(), set(), {}
    for d, ci, mid in pairs:
        if ci in used_c or mid in used_m:
            continue
        assign[mid] = (curves[ci], d); used_c.add(ci); used_m.add(mid)
    unassigned = [i for i in range(len(curves)) if i not in used_c]
    for mid, _, _, _ in METHODS:
        if mid not in mk:
            continue
        pts = sorted((m.x, m.y) for m in mk[mid])
        blocks.append((f'{mid}_{tag}_pts', pts))
        if mid in assign:
            blocks.append((f'{mid}_{tag}_curve', assign[mid][0].pts))
            if assign[mid][1] > 1.5:
                print(f'warn: panel {tag} {mid} curve-marker dist {assign[mid][1]:.2f}pt')
        else:
            print(f'warn: panel {tag} {mid} has markers but no curve')
    if unassigned:
        print(f'warn: panel {tag} {len(unassigned)} curves unassigned')
    cx, cy = ax.cal['x'], ax.cal['y']
    xt = [v for _, v in cx['pairs']]; yt = [v for _, v in cy['pairs']]
    cap = [t['s'] for t in fig.outside_texts() if t['y'] < ax.box[1] and t['y'] > ax.box[1] - 30 and ax.box[0] - 20 < t['x'] < ax.box[2] and t['s'].startswith('(')]
    info.append((tag, cx['lo'], cx['hi'], cy['lo'], cy['hi'], ' '.join('%g' % v for v in xt), ' '.join(sorted(mk)), cap[0] if cap else '?'))
F.write_blocks('recall-qps_main.dat', blocks)
# per-panel gnuplot commands (generated; loaded by recall-qps_main.gp)
ORDER = [M[0] for M in METHODS]
CHAR = {'rbqssd': 'CH_RTRI', 'fopq': 'CH_HEX'}     # no gnuplot point type -> character marker
with open('recall-qps_main_panels.gp', 'w') as f:
    f.write('# generated by extract_recall-qps_main.py -- do not edit by hand\n')
    for i, (tag, x0, x1, y0, y1, xt, ms, cap) in enumerate(info):
        r, c = divmod(i, 4)
        present = [m for m in ORDER if m in ms.split()]
        f.write(f'\n# ({tag})\n')
        f.write(f'eval PANEL(PXL({c}), PYB({r}), PW2, PH2)\n')
        for v in map(float, xt.split()):            # snap range ends onto ticks (tick at the edge must survive)
            if abs(x0 - v) < 2e-4: x0 = v
            if abs(x1 - v) < 2e-4: x1 = v
        f.write(f'set xrange [{x0:.6f}:{x1:.6f}]; set yrange [{y0:.5g}:{y1:.5g}]\n')
        f.write('set xtics (' + ', '.join(f'"{v}" {v}' for v in xt.split()) + ')\n')
        f.write('eval YLABEL("QPS")\n' if c == 0 else 'unset ylabel\n')
        capg = cap.replace('@', '\\\\\\\\@')
        f.write(f'eval XLABEL("{capg}")\n')
        parts = []
        for m in present:
            ls = ORDER.index(m) + 1
            parts.append(f'D index "{m}_{tag}_curve" u 1:2 w l ls {ls}')
        for m in present:
            ls = ORDER.index(m) + 1
            if m in CHAR:
                parts.append(f'D index "{m}_{tag}_pts" u 1:2:({CHAR[m]}) w labels center font ",".sprintf("%g",CHFS) tc ls {ls}')
            else:
                parts.append(f'D index "{m}_{tag}_pts" u 1:2 w p ls {ls} lw MLW')
        f.write('plot ' + ', \\\n     '.join(p_ + ' notitle' for p_ in parts) + '\n')
